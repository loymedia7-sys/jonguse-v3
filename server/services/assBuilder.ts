import { SubtitleProjectData, SubtitleItem, SubtitleStyle } from '../templates/presets';

/**
 * Converts decimal seconds to ASS timestamp format: H:MM:SS.cc (centiseconds)
 */
export function formatAssTime(seconds: number): string {
  const safeSec = Math.max(0, seconds);
  const h = Math.floor(safeSec / 3600);
  const m = Math.floor((safeSec % 3600) / 60);
  const s = Math.floor(safeSec % 60);
  const cs = Math.floor((safeSec % 1) * 100);

  return `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}.${String(cs).padStart(2, '0')}`;
}

/**
 * Converts hex color (#RRGGBB) to ASS color format &HBBGGRR&
 */
export function hexToAssColor(hex: string, alpha = '00'): string {
  if (!hex) return `&H${alpha}FFFFFF&`;
  let clean = hex.replace('#', '').trim();
  if (clean.length === 3) {
    clean = clean.split('').map((c) => c + c).join('');
  }
  if (clean.length !== 6) return `&H${alpha}FFFFFF&`;

  const r = clean.slice(0, 2);
  const g = clean.slice(2, 4);
  const b = clean.slice(4, 6);

  // ASS uses &HAABBGGRR (or &HBBGGRR without alpha)
  return `&H${alpha}${b}${g}${r}&`;
}

/**
 * Converts decimal seconds to SRT timestamp: HH:MM:SS,mmm
 */
export function formatSrtTime(seconds: number): string {
  const safeSec = Math.max(0, seconds);
  const h = Math.floor(safeSec / 3600);
  const m = Math.floor((safeSec % 3600) / 60);
  const s = Math.floor(safeSec % 60);
  const ms = Math.floor((safeSec % 1) * 1000);

  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')},${String(ms).padStart(3, '0')}`;
}

/**
 * Converts decimal seconds to VTT timestamp: HH:MM:SS.mmm
 */
export function formatVttTime(seconds: number): string {
  return formatSrtTime(seconds).replace(',', '.');
}

/**
 * Generates an Advanced SubStation Alpha (.ass) subtitle file content from SubtitleProjectData.
 */
export function generateAss(data: SubtitleProjectData, resX = 1280, resY = 720): string {
  const style = data.style || {
    font: 'Noto Sans Khmer',
    size: 44,
    color: '#FFFFFF',
    outline: '#000000',
    position: 'bottom',
  };

  const primaryCol = hexToAssColor(style.color || '#FFFFFF');
  const secondaryCol = hexToAssColor('#FFE600'); // for karaoke active sweep
  const outlineCol = hexToAssColor(style.outline || '#000000');
  const backCol = hexToAssColor(style.bgColor || '#000000', '60'); // with alpha

  // Alignment: 2 = Bottom-Center, 5 = Middle-Center, 8 = Top-Center
  const alignment = style.position === 'top' ? 8 : style.position === 'middle' ? 5 : 2;
  const marginV = style.positionYPercent ? Math.round(resY * (1 - style.positionYPercent / 100)) : 45;
  const outlineWidth = style.outlineWidth ?? 4;
  const shadowBlur = style.shadowBlur ?? 3;

  let ass = `[Script Info]
; Script generated by Jong Use (ចង់ប្រើ) Video Subtitle Styler
Title: Khmer Video Subtitles
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: ${resX}
PlayResY: ${resY}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,${style.font || 'Noto Sans Khmer'},${style.size || 44},${primaryCol},${secondaryCol},${outlineCol},${backCol},-1,0,0,0,100,100,1,0,1,${outlineWidth},${shadowBlur},${alignment},30,30,${marginV},1
Style: Highlight,${style.font || 'Noto Sans Khmer'},${(style.size || 44) + 2},${secondaryCol},${primaryCol},${outlineCol},${backCol},-1,0,0,0,105,105,1,0,1,${outlineWidth + 1},${shadowBlur + 2},${alignment},30,30,${marginV},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

  const template = data.template || 'karaoke-highlight';

  for (const item of data.subtitles) {
    const startStr = formatAssTime(item.start);
    const endStr = formatAssTime(item.end);
    let text = item.text.replace(/\r?\n/g, '\\N');

    const anim = style.animation || 'none';

    if (template === 'karaoke-highlight') {
      // If words are present, use karaoke \k<centiseconds> tags
      if (item.words && item.words.length > 0) {
        let karaokeText = '';
        for (const word of item.words) {
          const durationCs = Math.max(10, Math.round((word.e - word.s) * 100));
          karaokeText += `{\\k${durationCs}}${word.w} `;
        }
        text = karaokeText.trim();
      } else {
        // Fallback: split words and estimate
        const words = item.text.split(/\s+/);
        const totalCs = Math.max(20, Math.round((item.end - item.start) * 100));
        const perWord = Math.max(10, Math.floor(totalCs / Math.max(1, words.length)));
        text = words.map((w) => `{\\k${perWord}}${w}`).join(' ');
      }
    } else if (anim === 'none') {
      // Clean pop up style without any animation tags - solid, crisp, and high-visibility
      text = item.text.replace(/\r?\n/g, '\\N');
    } else if (anim === 'bounce') {
      text = `{\\t(0,140,\\frz-2.5)\\t(140,280,\\frz0)}${text}`;
    } else if (anim === 'fade') {
      text = `{\\fad(120,120)}${text}`;
    } else if (anim === 'pop') {
      text = `{\\t(0,120,\\fscx106\\fscy106)\\t(120,240,\\fscx100\\fscy100)}${text}`;
    }

    ass += `Dialogue: 0,${startStr},${endStr},Default,,0,0,0,,${text}\n`;
  }

  return ass;
}

/**
 * Generates standard SRT string from SubtitleProjectData
 */
export function generateSrt(data: SubtitleProjectData): string {
  return data.subtitles
    .map((item, idx) => {
      const num = idx + 1;
      const start = formatSrtTime(item.start);
      const end = formatSrtTime(item.end);
      return `${num}\n${start} --> ${end}\n${item.text}\n`;
    })
    .join('\n');
}

/**
 * Generates WebVTT string from SubtitleProjectData
 */
export function generateVtt(data: SubtitleProjectData): string {
  let vtt = 'WEBVTT\n\n';
  vtt += data.subtitles
    .map((item, idx) => {
      const num = idx + 1;
      const start = formatVttTime(item.start);
      const end = formatVttTime(item.end);
      return `${num}\n${start} --> ${end}\n${item.text}\n`;
    })
    .join('\n');
  return vtt;
}

/**
 * Parses SRT content into SubtitleItem[]
 */
export function parseSrtToSubtitles(srtText: string): SubtitleItem[] {
  if (!srtText || !srtText.trim()) return [];
  const normalized = srtText.replace(/\r\n/g, '\n').replace(/\r/g, '\n').trim();
  const blocks = normalized.split(/\n\n+/);
  const items: SubtitleItem[] = [];

  for (let idx = 0; idx < blocks.length; idx++) {
    const lines = blocks[idx].split('\n').map((l) => l.trim()).filter(Boolean);
    let timeLineIdx = -1;
    for (let i = 0; i < lines.length; i++) {
      if (lines[i].includes('-->')) {
        timeLineIdx = i;
        break;
      }
    }
    if (timeLineIdx === -1) continue;

    const [startStr, endStr] = lines[timeLineIdx].split('-->').map((s) => s.trim());
    const parseTimeSec = (str: string): number => {
      const cleaned = str.replace(',', '.');
      const parts = cleaned.split(':');
      if (parts.length === 3) {
        return parseInt(parts[0], 10) * 3600 + parseInt(parts[1], 10) * 60 + parseFloat(parts[2]);
      } else if (parts.length === 2) {
        return parseInt(parts[0], 10) * 60 + parseFloat(parts[1]);
      }
      return 0;
    };

    const start = parseTimeSec(startStr);
    const end = parseTimeSec(endStr);
    const text = lines.slice(timeLineIdx + 1).join('\n');

    items.push({
      id: idx + 1,
      start: Number(start.toFixed(2)),
      end: Number(end.toFixed(2)),
      text,
    });
  }

  return items;
}
